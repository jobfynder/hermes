# A category that says nothing (the bulk of the imported tail). Enrichment may replace these, and only these.
GENERIC_CATEGORIES = frozenset({"", "Tool/Technology", "Uncategorized"})


def _skill(subcategory, definition, recruiter, roles, relationships=(), category=None):
    row = {
        "subcategory": subcategory,
        "short_definition": definition,
        "recruiter_explanation": recruiter,
        "related_roles": list(roles),
    }
    if relationships:
        row["relationships"] = [{"type": kind, "skill": name} for kind, name in relationships]
    if category:
        row["category"] = category
    return row


