"""Reviewed glossary enrichment for the most requested staffing skills.

This is the canonical, human-reviewed source for `short_definition`, `recruiter_explanation`, `subcategory`,
`related_roles` and typed `relationships`. The backfill script applies it to a taxonomy file, and existing human-authored
values always win. Skills are keyed by their canonical taxonomy name.

Relationship types are a small controlled vocabulary. A relationship is context, never equivalence: a related skill must not
be counted as a match for a required one.
"""

